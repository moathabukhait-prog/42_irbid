#include "ft_printf.h"

int	ft_putnpr(int n)
{
	char	c;
	int		len;

	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return (11);
	}
	len = 0;
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
		len++;
	}
	if (n >= 10)
	{
		ft_putnpr(n / 10);
		n = n % 10 ;
		len++;
	}
	c = n + '0';
	write(1, &c, 1);
	return (len);
}
