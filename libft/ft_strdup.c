#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*copy;
	int		len;
	int		i;

	len = 0;
	while (s[len])
	{
		len++;
	}
	copy = malloc(len + 1);
	if (!copy)
		return (NULL);
	i = 0;
	while (s[i])
	{
		copy[i] = s[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
